RF_MAE_1H = 0.004033
RF_RMSE_1H = 0.005692
RF_DA_1H = 51.12
RF_F1_1H = 0.427
ARIMA_MAE_1H = 0.045971
ARIMA_RMSE_1H = 0.051331
ARIMA_DA_1H = 50.27
ARIMA_F1_1H = 0.488

# Quadrant counts (TP/TN/FP/FN, n=10000) solving the DA/F1 equations from
# fixtures.py's directional-scenario comment for the RF/ARIMA targets above,
# rounded to the nearest integer point (same method as fixtures.py's
# _DIR_COUNTS_1H/_DIR_COUNTS_6H). Verified empirically (scratch calc, not
