_RF_DIR_COUNTS = {"TP": 1821, "TN": 3291, "FP": 1709, "FN": 3179}
_ARIMA_DIR_COUNTS = {"TP": 2370, "TN": 2657, "FP": 2343, "FN": 2630}

_PREAMBLE_LEN = 50
_PURGE_GAP = 24  # thesis default (da-tese-ao-produto.md section 1.2): 24h purge gap.


def _with_preamble(target: pd.Series, seed: int) -> pd.Series:
    """Prepend `_PREAMBLE_LEN + _PURGE_GAP` filler points before `target` so a
    single-split `ValidationConfig(train_window=_PREAMBLE_LEN, ...,
    purge_gap=_PURGE_GAP)` run's ONE split covers exactly `train=filler`,
    `test=target` -- i.e. `target`'s values are what the real orchestrator
    scores, not a hand-picked subset. Filler values are tiny seeded noise
    (not a flat constant) purely so `metrics.mase`'s in-sample seasonal-naive
    denominator isn't a division-by-zero on a constant train segment; no
    assertion in this file depends on the filler's actual values, Naive0
    ignores `train` entirely, and the synthetic-forecast baselines below look
    up their prediction by index rather than reading `train`.
    """
    filler_n = _PREAMBLE_LEN + _PURGE_GAP
    filler_index = pd.date_range(
        end=target.index[0] - pd.Timedelta(hours=1), periods=filler_n, freq="h"
    )
    filler = pd.Series(
        np.random.default_rng(seed).normal(0.0, 1e-6, size=filler_n), index=filler_index
    )
    return pd.concat([filler, target])


def _single_split_config(target_len: int, extra_baselines: list) -> ValidationConfig:
    return ValidationConfig(
        train_window=_PREAMBLE_LEN,
        test_window=target_len,
        step=target_len,
        purge_gap=_PURGE_GAP,
        horizon=1,
        extra_baselines=extra_baselines,
    )


class _SyntheticForecast:
    """Looks up a precomputed, calibrated forecast for the split's test
    window by index rather than fitting a model -- see module disclosure
    point 2. Structurally satisfies the `Baseline` protocol.
    """

    def __init__(self, y_pred: pd.Series) -> None:
        self._y_pred = y_pred

    def predict(self, train: pd.Series, test: pd.Series) -> pd.Series:
        return self._y_pred.loc[test.index]


class _SyntheticOLS(_SyntheticForecast):
    pass


class _SyntheticRF(_SyntheticForecast):
    pass


class _SyntheticARIMA(_SyntheticForecast):
    pass


def _assert_naive0(baseline_results) -> None:
    m = baseline_results[NAIVE0_KEY].metrics
    assert m.mae == pytest.approx(NAIVE0_MAE_1H, abs=TOLERANCE)
    assert m.rmse == pytest.approx(NAIVE0_RMSE_1H, abs=TOLERANCE)


def _build_model_mae_rmse_scenario(
    seed_true_magnitude: int,
    seed_true_sign: int,
    seed_resid_magnitude: int,
    seed_resid_sign: int,
    model_mae: float,
    model_rmse: float,
    index: pd.DatetimeIndex,
) -> tuple[pd.Series, pd.Series]:
    """Generalizes `fixtures.build_1h_reference_scenario`'s OLS construction
    (Naive0-calibrated y_true, independently-calibrated residual, signed) to
    an arbitrary target (mae, rmse) pair, reusing fixtures.py's private
    calibration primitives rather than re-deriving the affine-rescale math.
    """
    true_magnitude = fixtures._calibrated_magnitudes(
        seed_true_magnitude, NAIVE0_MAE_1H, NAIVE0_RMSE_1H
    )
    y_true = pd.Series(
        fixtures._signed(true_magnitude, seed_true_sign), index=index, name="y_true"
    )
    resid_magnitude = fixtures._calibrated_magnitudes(
        seed_resid_magnitude, model_mae, model_rmse
    )
    resid = pd.Series(fixtures._signed(resid_magnitude, seed_resid_sign), index=index)
    y_pred = (y_true - resid).rename("y_pred")
    return y_true, y_pred


