# OLS DM verdict count (published 14 better / 22 worse) -- 36 synthetic
# per-split (Naive0, OLS) error pairs, replayed through the real
# splitter/baseline/DM pipeline (horizon=24), same plumbing as
# test_regression_6h.py's test_ols_dm_end_to_end, mixing K<1 ("better") and
# K>1 ("worse") splits to match the published mixed count.
#
# No RMSE is published at 24h (disclosure point 2), so the per-split error
# scale uses NAIVE0_MAE_24H directly -- an order-of-magnitude-appropriate
# spread, not a claim of reproducing any RMSE figure. This fixture verifies
# DM verdict counts only; MAE reproduction is handled separately above.

_DM_SPLIT_N = 500
_DM_SPLIT_NOISE_FRACTION = 0.05
_OLS_DM_KS_24H = [0.98] * 14 + [1.02] * 22  # published: 14 better / 22 worse
_OLS_DM_SEED_BASE_24H = 24100


def _build_dm_splits(ks: list[float], seed_base: int) -> list[fixtures.DMSplitErrors]:
    splits = []
    for i, k in enumerate(ks):
        rng = np.random.default_rng(seed_base + i)
        errors_naive0 = rng.normal(0.0, NAIVE0_MAE_24H, size=_DM_SPLIT_N)
        noise = rng.normal(0.0, _DM_SPLIT_NOISE_FRACTION * NAIVE0_MAE_24H, size=_DM_SPLIT_N)
        errors_model = k * errors_naive0 + noise
        index = pd.RangeIndex(_DM_SPLIT_N, name="point")
        splits.append(
            fixtures.DMSplitErrors(
                errors_naive0=pd.Series(errors_naive0, index=index, name="errors_naive0"),
                errors_model=pd.Series(errors_model, index=index, name="errors_model"),
            )
        )
    return splits


def _build_dm_series(ks: list[float], seed_base: int, seed_filler: int) -> tuple[pd.Series, pd.Series]:
    chunks = _build_dm_splits(ks, seed_base)
    test_w = _DM_SPLIT_N
    step = _PREAMBLE_LEN + _PURGE_GAP + test_w
    total_n = (len(chunks) - 1) * step + _PREAMBLE_LEN + _PURGE_GAP + test_w

    index = pd.date_range("2020-01-01", periods=total_n, freq="h")
    y_true = pd.Series(
        np.random.default_rng(seed_filler).normal(0.0, 1e-6, size=total_n), index=index
    )
    y_pred = y_true.copy()

    for k, chunk in enumerate(chunks):
        test_start_pos = k * step + _PREAMBLE_LEN + _PURGE_GAP
        idx_slice = index[test_start_pos : test_start_pos + test_w]
        # Naive0's forecast is always exactly 0, so errors_naive0 IS y_true on
        # this slice; y_pred is back-derived so that test - y_pred reproduces
        # errors_model exactly once the orchestrator recomputes it.
        errors_naive0 = chunk.errors_naive0.to_numpy()
        errors_model = chunk.errors_model.to_numpy()
        y_true.loc[idx_slice] = errors_naive0
        y_pred.loc[idx_slice] = errors_naive0 - errors_model

    return y_true, y_pred


def test_ols_dm_end_to_end():
    y_true, y_pred = _build_dm_series(_OLS_DM_KS_24H, _OLS_DM_SEED_BASE_24H, seed_filler=24200)
    test_w = _DM_SPLIT_N
    step = _PREAMBLE_LEN + _PURGE_GAP + test_w
    config = ValidationConfig(
        train_window=_PREAMBLE_LEN,
        test_window=test_w,
        step=step,
        purge_gap=_PURGE_GAP,
        horizon=_HORIZON,
        extra_baselines=[_SyntheticOLS(y_pred)],
    )

    results = run_validation_protocol(y_true, config)

    assert len(results) == len(_OLS_DM_KS_24H) == 36
    verdicts = [r.baseline_results["_SyntheticOLS"].dm_result.verdict for r in results]
    assert verdicts.count("better") == 14
    assert verdicts.count("worse") == 22  # published: 14 better / 22 worse


# ---------------------------------------------------------------------------
# Harvey correction demonstration (the acceptance-critical part of this
# ticket) -- see test_regression_6h.py's identical section for the full
# rationale on why an AR(1) construction guarantees genuine, non-trivial
# positive autocorrelation in the loss differential d_t = errors_model_t**2
# - errors_naive0_t**2 (i.i.d. draws, as used in the DM-verdict fixture
# above, would NOT exercise this -- gamma_k ~ 0 for all k>0 there).


def _ar1_errors(n: int, phi: float, sigma: float, seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    eps = rng.normal(0.0, sigma, size=n)
    e = np.empty(n)
    e[0] = eps[0]
    for t in range(1, n):
        e[t] = phi * e[t - 1] + eps[t]
    return e


def test_harvey_correction_changes_statistic_at_24h():
    errors_naive0 = _ar1_errors(n=300, phi=0.7, sigma=0.01, seed=778)
    noise = np.random.default_rng(779).normal(0.0, 0.0005, size=300)
    errors_model = 1.15 * errors_naive0 + noise

    result_h1 = dm_test_module.dm_test(errors_model, errors_naive0, horizon=1)
    result_h24 = dm_test_module.dm_test(errors_model, errors_naive0, horizon=_HORIZON)

    # Not just "different" within float noise -- the AR(1) autocorrelation
    # makes the Harvey correction move the statistic by a large, real
    # amount (empirically ~4.0 here), not a few ULPs.
    assert result_h24.statistic != pytest.approx(result_h1.statistic, abs=1e-3)
    assert abs(result_h24.statistic - result_h1.statistic) > 1.0
