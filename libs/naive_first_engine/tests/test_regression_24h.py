_OLS_DIR_COUNTS_24H = {"TP": 2708, "TN": 2372, "FP": 2628, "FN": 2292}
_RF_DIR_COUNTS_24H = {"TP": 2169, "TN": 2779, "FP": 2221, "FN": 2831}

_GAMMA_SHAPE = 0.8
_N = 2000
_PREAMBLE_LEN = 50
_PURGE_GAP = 24  # thesis default (da-tese-ao-produto.md section 1.2): 24h purge gap, independent of horizon.
_HORIZON = 24


def _with_preamble(target: pd.Series, seed: int) -> pd.Series:
    """Identical construction to test_regression_1h.py's `_with_preamble` --
    see that file for the full rationale. Duplicated here rather than
    imported per the ticket's Design section (minor duplication across the
    per-horizon regression files is an accepted, documented trade-off).
    """
    filler_n = _PREAMBLE_LEN + _PURGE_GAP
    filler_index = pd.date_range(
        end=target.index[0] - pd.Timedelta(hours=1), periods=filler_n, freq="h"
    )
    filler = pd.Series(
        np.random.default_rng(seed).normal(0.0, 1e-6, size=filler_n), index=filler_index
    )
    return pd.concat([filler, target])


def _single_split_config(target_len: int, extra_baselines: list) -> ValidationConfig:
    return ValidationConfig(
        train_window=_PREAMBLE_LEN,
        test_window=target_len,
        step=target_len,
        purge_gap=_PURGE_GAP,
        horizon=_HORIZON,
        extra_baselines=extra_baselines,
    )


class _SyntheticForecast:
    """Looks up a precomputed, calibrated forecast for the split's test
    window by index rather than fitting a model. Structurally satisfies the
    `Baseline` protocol.
    """

    def __init__(self, y_pred: pd.Series) -> None:
        self._y_pred = y_pred

    def predict(self, train: pd.Series, test: pd.Series) -> pd.Series:
        return self._y_pred.loc[test.index]


class _SyntheticOLS(_SyntheticForecast):
    pass


class _SyntheticRF(_SyntheticForecast):
    pass


def _assert_naive0(baseline_results) -> None:
    m = baseline_results[NAIVE0_KEY].metrics
    assert m.mae == pytest.approx(NAIVE0_MAE_24H, abs=TOLERANCE)


def _calibrated_magnitude_mean_only(seed: int, target_mean: float) -> np.ndarray:
    """Non-negative array whose mean exactly equals `target_mean`. See
    test_regression_6h.py's identical helper for the full rationale (no
    RMSE published at this horizon, so only a one-parameter rescale is
    solved, not `fixtures._calibrated_magnitudes`'s two-parameter one).
    """
    rng = np.random.default_rng(seed)
    x = rng.gamma(shape=_GAMMA_SHAPE, scale=1.0, size=_N)
    magnitudes = x * (target_mean / x.mean())
    assert magnitudes.min() >= 0, "calibration produced a negative magnitude"
    return magnitudes


def _build_model_mae_scenario(
    seed_true_magnitude: int,
    seed_true_sign: int,
    seed_resid_magnitude: int,
    seed_resid_sign: int,
    model_mae: float,
    index: pd.DatetimeIndex,
) -> tuple[pd.Series, pd.Series]:
    true_magnitude = _calibrated_magnitude_mean_only(seed_true_magnitude, NAIVE0_MAE_24H)
    y_true = pd.Series(
        fixtures._signed(true_magnitude, seed_true_sign), index=index, name="y_true"
    )
    resid_magnitude = _calibrated_magnitude_mean_only(seed_resid_magnitude, model_mae)
    resid = pd.Series(fixtures._signed(resid_magnitude, seed_resid_sign), index=index)
    y_pred = (y_true - resid).rename("y_pred")
    return y_true, y_pred


